import React, { useState } from 'react';
import { X, Download, Copy, Check, FileText } from 'lucide-react';
import { FoodDiaryEntry, MacroNutrients } from '../../types';

interface Props {
  isOpen: boolean;
  onClose: () => void;
  dateLabel: string;
  entries: FoodDiaryEntry[];
  calorieBudget: {
    dailyTarget: number;
    caloriesLeft: number;
    caloriesConsumed: number;
    caloriesBurned: number;
    macrosLeft: MacroNutrients;
    macrosTotal: MacroNutrients;
  };
}

export const ExportSummaryModal: React.FC<Props> = ({
  isOpen,
  onClose,
  dateLabel,
  entries,
  calorieBudget
}) => {
  const [copied, setCopied] = useState(false);

  if (!isOpen) return null;

  const totalCalories = entries.reduce((acc, curr) => acc + curr.calories, 0);
  const totalP = entries.reduce((acc, curr) => acc + curr.macros.protein, 0);
  const totalC = entries.reduce((acc, curr) => acc + curr.macros.carbs, 0);
  const totalF = entries.reduce((acc, curr) => acc + curr.macros.fat, 0);
  const totalFib = entries.reduce((acc, curr) => acc + curr.macros.fibre, 0);

  const formattedText = `=========================================
PULSEFIT & NOURISH - DAILY DIARY REPORT
Date: ${dateLabel}
=========================================

NUTRITION SUMMARY:
• Daily Target: ${calorieBudget.dailyTarget} kcal
• Total Consumed: ${totalCalories} kcal
• Calories Burned: ${calorieBudget.caloriesBurned} kcal
• Net Calories Remaining: ${calorieBudget.caloriesLeft} kcal

MACRONUTRIENT TOTALS:
• Protein: ${totalP}g / ${calorieBudget.macrosTotal.protein}g (${Math.round((totalP / calorieBudget.macrosTotal.protein) * 100)}%)
• Carbohydrates: ${totalC}g / ${calorieBudget.macrosTotal.carbs}g (${Math.round((totalC / calorieBudget.macrosTotal.carbs) * 100)}%)
• Fats: ${totalF}g / ${calorieBudget.macrosTotal.fat}g (${Math.round((totalF / calorieBudget.macrosTotal.fat) * 100)}%)
• Dietary Fibre: ${totalFib}g / ${calorieBudget.macrosTotal.fibre}g (${Math.round((totalFib / calorieBudget.macrosTotal.fibre) * 100)}%)

LOGGED MEAL ITEMS (${entries.length}):
${entries.map((e, idx) => `${idx + 1}. [${e.mealCategory}] ${e.name} - ${e.calories} kcal (${e.portion}) | P: ${e.macros.protein}g, C: ${e.macros.carbs}g, F: ${e.macros.fat}g`).join('\n')}

Generated by PulseFit & Nourish
=========================================`;

  const handleCopy = () => {
    navigator.clipboard.writeText(formattedText);
    setCopied(true);
    setTimeout(() => setCopied(false), 2500);
  };

  const handleDownload = () => {
    const blob = new Blob([formattedText], { type: 'text/plain;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = `nutrition-report-${dateLabel.toLowerCase().replace(/[^a-z0-9]/g, '-')}.txt`;
    link.click();
    URL.revokeObjectURL(url);
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/80 backdrop-blur-md animate-in fade-in duration-200">
      <div className="relative w-full max-w-xl max-h-[85vh] flex flex-col bg-slate-900 border border-slate-750 rounded-2xl shadow-2xl overflow-hidden text-slate-100">
        
        {/* Header */}
        <div className="p-4 sm:p-5 border-b border-slate-800 flex items-center justify-between bg-slate-900/90">
          <div className="flex items-center gap-2.5">
            <div className="w-9 h-9 rounded-xl bg-cyan-500/15 text-cyan-400 flex items-center justify-center">
              <FileText className="w-5 h-5" />
            </div>
            <div>
              <h2 className="text-lg font-bold text-white">Daily Nutrition Report</h2>
              <p className="text-xs text-slate-400">{dateLabel} • {entries.length} items logged</p>
            </div>
          </div>
          <button
            onClick={onClose}
            className="w-8 h-8 rounded-lg hover:bg-slate-800 text-slate-400 hover:text-white flex items-center justify-center"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Text Preview */}
        <div className="p-5 overflow-y-auto flex-1 font-mono text-xs text-slate-300 bg-slate-950/80 m-4 rounded-xl border border-slate-800 whitespace-pre-wrap leading-relaxed select-all">
          {formattedText}
        </div>

        {/* Footer */}
        <div className="p-4 border-t border-slate-800 bg-slate-900 flex items-center justify-between">
          <button
            onClick={handleDownload}
            className="px-4 py-2 rounded-xl bg-slate-800 hover:bg-slate-750 text-slate-200 hover:text-white text-xs font-semibold flex items-center gap-2 border border-slate-700 transition-colors"
          >
            <Download className="w-4 h-4 text-cyan-400" />
            Download .TXT
          </button>

          <button
            onClick={handleCopy}
            className="px-5 py-2 rounded-xl bg-emerald-500 hover:bg-emerald-400 text-slate-950 text-xs font-bold flex items-center gap-2 shadow-lg shadow-emerald-500/20 transition-all"
          >
            {copied ? <Check className="w-4 h-4 stroke-[3]" /> : <Copy className="w-4 h-4" />}
            {copied ? 'Copied to Clipboard!' : 'Copy Summary'}
          </button>
        </div>
      </div>
    </div>
  );
};
